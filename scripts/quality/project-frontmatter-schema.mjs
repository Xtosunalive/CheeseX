#!/usr/bin/env node
// project-frontmatter-schema.mjs — entity-frontmatter-schema.md 派生投影生成器（ADR-008 D2）
// @responsible: 从 知识库/TheSchema/fields.yaml（字段唯一机器源）＋enums.yaml（值域唯一源）生成
//               vault 侧 entity-frontmatter-schema.md 只读投影——消灭手维护副本（防口径漂移）。
// @inputs: vault（经 VAULT_PATH/.env 解析）
// @outputs: 重写 知识库/TheSchema/entity-frontmatter-schema.md；--check 只读比对（CI/门禁用）
// @context: SPEC-015 §三.2；确定性生成（同输入同输出字节一致——连续两遍 diff 为空为验收）。
// 写者登记：本脚本是 fields.yaml 投影的显式授权写者（schema-rules-data 域 write_protocol）。
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { resolveTheSchemaDir } from "./shared/theschema-root.mjs";

const require = createRequire(import.meta.url);
const { replaceTheSchemaFile } = require("../../server/shared/theschema-write.cjs"); // WP-079 唯一门：TheSchema 投影写也走咽喉（内部即目的地执法网关），服务与生成器一律不自判通道
const YAML = require("yaml");
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

function resolveVault() {
  const fromEnv = process.env.VAULT_PATH;
  if (fromEnv && fs.existsSync(fromEnv)) return fromEnv;
  const envPath = path.join(ROOT, ".env");
  if (!fs.existsSync(envPath)) return null;
  const line = fs.readFileSync(envPath, "utf8").split("\n").find((l) => l.trim().startsWith("VAULT_PATH="));
  if (!line) return null;
  const v = line.split("=").slice(1).join("=").trim().replace(/^["']|["']$/g, "");
  return v && fs.existsSync(v) ? v : null;
}

const LAYER_ORDER = ["管理属性", "业务属性", "内容属性"];
const LAYER_INTENT = {
  管理属性: "生命周期控制——管理「这段知识是否有效」",
  业务属性: "架构图渲染＋拓扑生成——决定「在架构图哪里怎么展示」",
  内容属性: "搜索＋标签＋辅助——服务「怎么被找到」",
};

function valueDomainText(field) {
  const vd = field.value_domain;
  if (!vd) return "—";
  const src = vd.segment ? `${vd.source}（${vd.segment}）` : vd.source === "free" ? "自由文本" : `enums.${vd.source}`;
  const note = vd.note ? `：${vd.note}` : "";
  return `${src}${note}`;
}

function fieldRow(field) {
  const scope = field.scope.join("＋");
  const aliases = field.aliases?.length ? `（兼容写法：${field.aliases.join("、")}）` : "";
  return `| \`${field.name}\` | ${field.type} | ${field.required} | ${scope} | ${valueDomainText(field)} | ${field.label}${aliases}——${field.description} |`;
}

export function buildProjection({ fields, enums }) {
  const layers = (enums.layers || []).filter((l) => l && l.id && l.entity_layer !== false);
  const layerAliases = enums.architecture_projection?.layer_aliases || {};
  const lines = [];
  lines.push("# 实体 Frontmatter 字段 Schema");
  lines.push("");
  lines.push("> **派生物标记**：本文件由 `scripts/quality/project-frontmatter-schema.mjs` 从 `知识库/TheSchema/fields.yaml`（字段唯一机器源）与 `enums.yaml`（值域唯一源）生成——**禁止手改**。字段增删改请改 fields.yaml 后重跑 `npm run project:frontmatter-schema`。");
  lines.push("> Generated by project-frontmatter-schema（ADR-008 D2）");
  lines.push("");
  lines.push("## 一、字段总表");
  lines.push("");
  for (const layer of LAYER_ORDER) {
    const group = fields.filter((f) => f.layer === layer);
    if (!group.length) continue;
    lines.push(`### ${layer}（${LAYER_INTENT[layer]}）`);
    lines.push("");
    lines.push("| 字段 | 类型 | 必填 | 作用域 | 值域 | 说明 |");
    lines.push("|------|------|------|--------|------|------|");
    for (const field of group) lines.push(fieldRow(field));
    lines.push("");
  }
  lines.push("## 二、`arch_layer` 合法值（enums.yaml layers 派生）");
  lines.push("");
  lines.push("| 值 | 含义 | SA 颜色 |");
  lines.push("|----|------|---------|");
  for (const layer of layers) lines.push(`| \`${layer.id}\` | ${layer.label} | ${layer.color} |`);
  lines.push("");
  const aliasEntries = Object.entries(layerAliases);
  if (aliasEntries.length) {
    lines.push("> 兼容别名集中定义在 `enums.yaml` 的 `architecture_projection.layer_aliases`：");
    lines.push("> " + aliasEntries.map(([alias, target]) => `\`${alias}\`→\`${target}\``).join("、"));
    lines.push("> 同步/审计/校验时自动归一化。");
    lines.push("");
  }
  lines.push("## 三、同名分立说明");
  lines.push("");
  lines.push("- `status`：实体侧=Obsidian 页面状态（有效/已归档/制定中）；文章侧=文档生命周期（enums lifecycle.status，新建缺省 lifecycle.default_status）——同名不同值域，按作用域分立。");
  lines.push("- `module`：文章侧必填、实体侧建议（匹配名列表，wikilink 引用自动剥离）。");
  lines.push("- `category-path`：文章侧必填、实体侧建议；三段式 domain:subdomain:topic 契约见 article-validator-lib.cjs（PR-046 语义；SPEC-022 起 Node 单源）。");
  lines.push("");
  return lines.join("\n") + "\n";
}

function main() {
  const vault = resolveVault();
  if (!vault) {
    if (process.argv.includes("--check")) {
      // CI 门禁阶段先于 e2e vault 构建（check-fields-registry/schema-writers 同款先例）：
      // 无 vault＝无对账面，明示 skip；本地/有 vault 环境跑真比对（生成器即校验器）。
      console.log("project-frontmatter-schema --check: (skip VAULT_PATH 未解析——本环境无投影对账面)");
      return;
    }
    console.error("project-frontmatter-schema: VAULT_PATH 未解析（环境变量或 .env）——无法生成投影");
    process.exit(1);
  }
  // WP-049 余量批：两件经词表装载端口（raw 同旧裸 parse；缺 fields＝显式退出、缺 enums＝{} 保持）
  const { loadVocabBundle } = require("../../server/shared/vocab-load-port.cjs");
  const vocab = loadVocabBundle(vault, { files: ["fields", "enums"] });
  const fieldsFile = vocab.files.fields;
  const target = path.join(resolveTheSchemaDir(vault), "entity-frontmatter-schema.md");
  if (!fieldsFile || fieldsFile.state !== "present") {
    console.error(`project-frontmatter-schema: fields.yaml 不存在（${resolveTheSchemaDir(vault)}）——先落档字段字典`);
    process.exit(1);
  }
  const fields = (fieldsFile.raw || {}).fields || [];
  const enumsFile = vocab.files.enums;
  const enums = enumsFile && enumsFile.state === "present" ? (enumsFile.raw || {}) : {};
  const output = buildProjection({ fields, enums });

  if (process.argv.includes("--check")) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (current !== output) {
      console.error("project-frontmatter-schema --check: 投影漂移（vault 文档与 fields.yaml 不一致）——重跑 npm run project:frontmatter-schema");
      process.exit(1);
    }
    console.log("project-frontmatter-schema --check: ok（投影与字段字典一致）");
    return;
  }
  replaceTheSchemaFile(target, output, { summary: "投影重生成（TheSchema 主源）" }); // 唯一门：钉扎领地外／vault 侧未钉扎一律拒写
  console.log(`project-frontmatter-schema: 已生成 ${path.relative(vault, target)}（${fields.length} 字段）`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
